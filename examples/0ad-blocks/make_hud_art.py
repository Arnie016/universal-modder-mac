def from_map(text: str) -> Image.Image:
    rows = [r for r in text.strip("\n").splitlines()]
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            img.putpixel((x, y), PALETTE[ch])
    return img


def cube(top: tuple, left: tuple, right: tuple, seed: int) -> Image.Image:
    """An isometric 16x16 block, speckled like stone."""
    rng = random.Random(seed)
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))

    def speckle(c):
        j = rng.randint(-18, 18)
        return tuple(max(0, min(255, v + j)) for v in c[:3]) + (255,)

    def inside(px, py, poly):
        hit = False
        for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]):
            if (y1 > py) != (y2 > py) and px < (x2 - x1) * (py - y1) / (y2 - y1) + x1:
                hit = not hit
        return hit

    faces = (
        ([(8, 0), (16, 4), (8, 8), (0, 4)], top),
        ([(0, 4), (8, 8), (8, 16), (0, 12)], left),
        ([(8, 8), (16, 4), (16, 12), (8, 16)], right),
    )
    for y in range(16):
        for x in range(16):
            for poly, colour in faces:
                if inside(x + 0.5, y + 0.5, poly):
                    img.putpixel((x, y), speckle(colour))
                    break
    # outline
    out = img.copy()
    for y in range(16):
        for x in range(16):
            if img.getpixel((x, y))[3] == 0:
                continue
            for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
                if not (0 <= nx < 16 and 0 <= ny < 16) or img.getpixel((nx, ny))[3] == 0:
                    out.putpixel((x, y), PALETTE["k"])
                    break
    return out


def frame(size: int, border: int, edge: tuple, fill: tuple, light: tuple | None = None) -> Image.Image:
    img = Image.new("RGBA", (size, size), fill)
    for y in range(size):
        for x in range(size):
            if x < border or y < border or x >= size - border or y >= size - border:
                img.putpixel((x, y), edge)
            elif light and (x < border * 2 or y < border * 2):
                img.putpixel((x, y), light)
    return img


